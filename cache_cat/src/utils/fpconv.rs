/// 10^9 down to 1: the divisors for the integral part, which has 32 bits.
const TENS: [u64; 10] = [
    1_000_000_000,
    100_000_000,
    10_000_000,
    1_000_000,
    100_000,
    10_000,
    1_000,
    100,
    10,
    1,
];

/// The cached power that brings a value with binary exponent `exp` into the
/// window Grisu works in, and its decimal exponent.
fn find_cached_pow10(exp: i32) -> (Fp, i32) {
    const ONE_LOG_TEN: f64 = 0.30102999566398114;

    // Truncated toward zero twice, as the C conversions to `int` do.
    let approx = (f64::from(-(exp + NPOWERS)) * ONE_LOG_TEN) as i32;
    let mut idx = (approx - FIRST_POWER) / STEP_POWERS;

    loop {
        let power = POWERS_TEN[idx as usize];
        let current = exp + power.exp + 64;
        if current < EXP_MIN {
            idx += 1;
        } else if current > EXP_MAX {
            idx -= 1;
        } else {
            return (power, FIRST_POWER + idx * STEP_POWERS);
        }
    }
}

fn build_fp(bits: u64) -> Fp {
    let frac = bits & FRAC_MASK;
    let exp = ((bits & EXP_MASK) >> 52) as i32;
    if exp != 0 {
        fp(frac + HIDDEN_BIT, exp - EXP_BIAS)
    } else {
        fp(frac, -EXP_BIAS + 1)
    }
}

fn normalize(mut value: Fp) -> Fp {
    while value.frac & HIDDEN_BIT == 0 {
        value.frac <<= 1;
        value.exp -= 1;
    }

    let shift = 64 - 52 - 1;
    value.frac <<= shift;
    value.exp -= shift;
    value
}

/// Halfway points to the neighbouring doubles, as `(lower, upper)` with one
/// shared exponent.
fn normalized_boundaries(value: Fp) -> (Fp, Fp) {
    let mut upper = fp((value.frac << 1) + 1, value.exp - 1);
    while upper.frac & (HIDDEN_BIT << 1) == 0 {
        upper.frac <<= 1;
        upper.exp -= 1;
    }

    let u_shift = 64 - 52 - 2;
    upper.frac <<= u_shift;
    upper.exp -= u_shift;

    // The double below a power of two is only half as far away.
    let l_shift = if value.frac == HIDDEN_BIT { 2 } else { 1 };
    let mut lower = fp((value.frac << l_shift) - 1, value.exp - l_shift);
    lower.frac <<= lower.exp - upper.exp;
    lower.exp = upper.exp;

    (lower, upper)
}

fn multiply(a: Fp, b: Fp) -> Fp {
    const LO_MASK: u64 = 0x0000_0000_FFFF_FFFF;

    let ah_bl = (a.frac >> 32) * (b.frac & LO_MASK);
    let al_bh = (a.frac & LO_MASK) * (b.frac >> 32);
    let al_bl = (a.frac & LO_MASK) * (b.frac & LO_MASK);
    let ah_bh = (a.frac >> 32) * (b.frac >> 32);

    let mut tmp = (ah_bl & LO_MASK) + (al_bh & LO_MASK) + (al_bl >> 32);
    // Round up.
    tmp += 1 << 31;

    fp(
        ah_bh + (ah_bl >> 32) + (al_bh >> 32) + (tmp >> 32),
        a.exp + b.exp + 64,
    )
}

/// Lowers the last digit while that moves the text closer to the value.
///
/// `&&` and `||` short-circuit as in C, so no subtraction here can wrap.
fn round_digit(digits: &mut [u8], delta: u64, mut rem: u64, kappa: u64, frac: u64) {
    while rem < frac
        && delta - rem >= kappa
        && (rem + kappa < frac || frac - rem > rem + kappa - frac)
    {
        digits[digits.len() - 1] -= 1;
        rem += kappa;
    }
}

/// Writes the digits of `upper` until the rest fits between the boundaries,
/// and returns how many there are. `k` receives the decimal exponent.
fn generate_digits(value: Fp, upper: Fp, lower: Fp, digits: &mut [u8; 18], k: &mut i32) -> usize {
    let wfrac = upper.frac - value.frac;
    let mut delta = upper.frac - lower.frac;

    let shift = -upper.exp;
    let one_frac = 1u64 << shift;

    let mut part1 = upper.frac >> shift;
    let mut part2 = upper.frac & (one_frac - 1);

    let mut idx = 0;
    let mut kappa = 10;
    for div in TENS {
        let digit = part1 / div;
        if digit != 0 || idx != 0 {
            digits[idx] = digit as u8 + b'0';
            idx += 1;
        }

        part1 -= digit * div;
        kappa -= 1;

        let tmp = (part1 << shift) + part2;
        if tmp <= delta {
            *k += kappa;
            // The shift drops high bits here exactly as it does in C.
            round_digit(&mut digits[..idx], delta, tmp, div << shift, wfrac);
            return idx;
        }
    }

    // C walks back through its table of tens instead: 10, 100, ...
    let mut unit = 10;
    loop {
        part2 *= 10;
        delta *= 10;
        kappa -= 1;

        let digit = part2 >> shift;
        if digit != 0 || idx != 0 {
            digits[idx] = digit as u8 + b'0';
            idx += 1;
        }

        part2 &= one_frac - 1;
        if part2 < delta {
            *k += kappa;
            round_digit(&mut digits[..idx], delta, part2, one_frac, wfrac * unit);
            return idx;
        }

        unit *= 10;
    }
}

/// Digits and decimal exponent of a finite, non-zero double: the value is
/// `digits * 10^k`.
fn grisu2(bits: u64, digits: &mut [u8; 18]) -> (usize, i32) {
    let value = build_fp(bits);
    let (lower, upper) = normalized_boundaries(value);
    let value = normalize(value);

    let (cached, k) = find_cached_pow10(upper.exp);

    let value = multiply(value, cached);
    let mut upper = multiply(upper, cached);
    let mut lower = multiply(lower, cached);

    lower.frac += 1;
    upper.frac -= 1;

    let mut exponent = -k;
    let ndigits = generate_digits(value, upper, lower, digits, &mut exponent);
    (ndigits, exponent)
}

/// Lays the digits out as an integer, a plain decimal or in scientific
/// notation, and returns the length written.
fn emit_digits(digits: &[u8], dest: &mut [u8], k: i32, negative: bool) -> usize {
    let len = digits.len();
    let ndigits = len as i32;
    let mut exp = (k + ndigits - 1).abs();

    // Plain integer.
    if k >= 0 && exp < ndigits + 7 {
        let zeroes = k as usize;
        dest[..len].copy_from_slice(digits);
        dest[len..len + zeroes].fill(b'0');
        return len + zeroes;
    }

    // Decimal without scientific notation.
    if k < 0 && (k > -7 || exp < 4) {
        let offset = ndigits - k.abs();
        if offset <= 0 {
            // Below one: a leading zero, then the zeroes after the point.
            let zeroes = (-offset) as usize;
            dest[0] = b'0';
            dest[1] = b'.';
            dest[2..2 + zeroes].fill(b'0');
            dest[2 + zeroes..2 + zeroes + len].copy_from_slice(digits);
            return len + 2 + zeroes;
        }
        let offset = offset as usize;
        dest[..offset].copy_from_slice(&digits[..offset]);
        dest[offset] = b'.';
        dest[offset + 1..len + 1].copy_from_slice(&digits[offset..]);
        return len + 1;
    }

    // Decimal with scientific notation.
    let ndigits = ndigits.min(18 - i32::from(negative));
    let len = ndigits as usize;

    let mut idx = 0;
    dest[idx] = digits[0];
    idx += 1;

    if len > 1 {
        dest[idx] = b'.';
        idx += 1;
        dest[idx..idx + len - 1].copy_from_slice(&digits[1..len]);
        idx += len - 1;
    }

    dest[idx] = b'e';
    idx += 1;
    dest[idx] = if k + ndigits - 1 < 0 { b'-' } else { b'+' };
    idx += 1;

    // The exponent has no leading zero and up to three digits.
    let mut cent = 0;
    if exp > 99 {
        cent = exp / 100;
        dest[idx] = cent as u8 + b'0';
        idx += 1;
        exp -= cent * 100;
    }
    if exp > 9 {
        let dec = exp / 10;
        dest[idx] = dec as u8 + b'0';
        idx += 1;
        exp -= dec * 10;
    } else if cent != 0 {
        dest[idx] = b'0';
        idx += 1;
    }
    dest[idx] = (exp % 10) as u8 + b'0';
    idx + 1
}

/// Writes `value` as `fpconv_dtoa` does and returns the length of the text.
pub(crate) fn dtoa(value: f64, dest: &mut [u8; MAX_LEN]) -> usize {
    let bits = value.to_bits();
    let negative = bits & SIGN_MASK != 0;
    let mut len = 0;
    if negative {
        dest[0] = b'-';
        len = 1;
    }
    let dest = &mut dest[len..];

    // Zero, NaN and infinity have no digits to generate.
    if value == 0.0 {
        dest[0] = b'0';
        return len + 1;
    }
    if bits & EXP_MASK == EXP_MASK {
        let text = if bits & FRAC_MASK != 0 {
            b"nan"
        } else {
            b"inf"
        };
        dest[..3].copy_from_slice(text);
        return len + 3;
    }

    let mut digits = [0; 18];
    let (ndigits, k) = grisu2(bits, &mut digits);
    len + emit_digits(&digits[..ndigits], dest, k, negative)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn text(value: f64) -> String {
        let mut dest = [0; MAX_LEN];
        let len = dtoa(value, &mut dest);
        String::from_utf8(dest[..len].to_vec()).unwrap()
    }

    #[test]
    fn notation_depends_on_the_digit_count_and_the_decimal_exponent() {
        for (value, expected) in [
            // An integer while fewer than eight zeroes follow the digits.
            (100.0, "100"),
            (1e7, "10000000"),
            (9223372036854775808.0, "9223372036854776000"),
            (1.2345678901234567e23, "123456789012345670000000"),
            // Scientific from there on, with a signed exponent of any width.
            (1e8, "1e+8"),
            (9.5e18, "9.5e+18"),
            (1e21, "1e+21"),
            (1.5e300, "1.5e+300"),
            (f64::MAX, "1.7976931348623157e+308"),
            // A plain decimal down to 0.001, whatever the number of digits.
            (0.1, "0.1"),
            (2.5, "2.5"),
            (123.456, "123.456"),
            (13.361389338970184, "13.361389338970184"),
            (3.0000000000000004, "3.0000000000000004"),
            (0.001, "0.001"),
            // Below that only while the last digit is within six places.
            (0.000015, "0.000015"),
            (0.000001, "0.000001"),
            (0.00012345, "1.2345e-4"),
            (9.924173355102539e-5, "9.924173355102539e-5"),
            (1e-7, "1e-7"),
            (1e-100, "1e-100"),
            (f64::MIN_POSITIVE, "2.2250738585072014e-308"),
            (5e-324, "5e-324"),
            // The sign comes first; this is the longest text there is.
            (-1.0012148579363611e-4, "-1.0012148579363611e-4"),
            (-1.2345678901234567e23, "-123456789012345670000000"),
        ] {
            assert_eq!(text(value), expected);
        }
    }

    #[test]
    fn zero_nan_and_infinity_have_fixed_texts() {
        assert_eq!(text(0.0), "0");
        assert_eq!(text(-0.0), "-0");
        assert_eq!(text(f64::INFINITY), "inf");
        assert_eq!(text(f64::NEG_INFINITY), "-inf");
        assert_eq!(text(f64::NAN.copysign(1.0)), "nan");
    }

    #[test]
    fn a_decimal_on_the_boundary_between_two_doubles_is_not_shortened() {
        // 1726839e14 is exactly halfway between two doubles. It parses to this
        // one, but Grisu2 leaves the boundaries out and writes all 17 digits.
        let value: f64 = "1.726839e20".parse().unwrap();
        assert_eq!(value.to_bits(), 0x4422_b8f0_e843_5228);
        assert_eq!(text(value), "172683900000000020000");
    }

    /// Significant digits without sign, point, exponent and outer zeroes.
    fn significant(text: &str) -> String {
        let mantissa = text.split('e').next().unwrap();
        let digits: String = mantissa.chars().filter(char::is_ascii_digit).collect();
        digits.trim_matches('0').to_string()
    }

    #[test]
    fn every_text_parses_back_and_is_nearly_always_the_shortest() {
        let mut state = 1u64;
        let mut random = move || {
            state = state.wrapping_add(0x9E37_79B9_7F4A_7C15);
            let mut z = state;
            z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
            z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
            z ^ (z >> 31)
        };

        let (mut total, mut longer) = (0, 0);
        // Every binary exponent, subnormals included.
        for exponent in 0..2047u64 {
            let fractions = [
                0,
                1,
                FRAC_MASK,
                1 << 51,
                random() & FRAC_MASK,
                random() & FRAC_MASK,
            ];
            for fraction in fractions {
                for sign in [0, SIGN_MASK] {
                    let value = f64::from_bits(sign | exponent << 52 | fraction);
                    if value == 0.0 {
                        continue;
                    }
                    let text = text(value);
                    assert!(text.len() <= 25, "{text}");
                    assert_eq!(
                        text.parse::<f64>().unwrap().to_bits(),
                        value.to_bits(),
                        "{text}"
                    );
                    total += 1;
                    longer += usize::from(significant(&text) != significant(&format!("{value:e}")));
                }
            }
        }
        // Grisu2 misses the shortest digits only for a small share of doubles.
        assert!(longer * 100 < total, "{longer} of {total}");
    }
}
