/// Room for the longest text: a sign, 17 digits and 7 zeroes are 25 bytes.
pub(crate) const MAX_LEN: usize = 32;

const FRAC_MASK: u64 = 0x000F_FFFF_FFFF_FFFF;
const EXP_MASK: u64 = 0x7FF0_0000_0000_0000;
const HIDDEN_BIT: u64 = 0x0010_0000_0000_0000;
const SIGN_MASK: u64 = 0x8000_0000_0000_0000;
const EXP_BIAS: i32 = 1023 + 52;

/// The value `frac * 2^exp`.
#[derive(Clone, Copy)]
struct Fp {
    frac: u64,
    exp: i32,
}

const fn fp(frac: u64, exp: i32) -> Fp {
    Fp { frac, exp }
}

const NPOWERS: i32 = 87;
const STEP_POWERS: i32 = 8;
/// The table starts at 10^-348.
const FIRST_POWER: i32 = -348;
const EXP_MAX: i32 = -32;
const EXP_MIN: i32 = -60;

